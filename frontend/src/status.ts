import type { Result, Status } from './api';

/**
 * Человеческие названия статусов.
 *
 * «review» — это не «ошибка» и не «нет ответа»: модель нашла позицию, но её
 * уверенность ниже порога `ok`. На реальных выгрузках (эксп. 30) в этой полосе
 * 26 из 29 строк содержали верный код, поэтому подпись говорит «нашёл, но не
 * уверен», а не «требует проверки» — второе читалось как «не нашёл».
 *
 * «not_found» — это «нет в перечне», а не «сервис не работает»: перечень
 * закрытый, и молчание — корректный ответ для товара, которого в нём нет.
 */
export const STATUS_LABEL: Record<Status, string> = {
  ok: 'Уверенный результат',
  review: 'Нашёл, но не уверен',
  not_found: 'Нет в перечне',
};

export const STATUS_HELP: Record<Status, string> = {
  ok: 'Модель нашла подходящий код. Всё равно проверьте его по постановлению.',
  review: 'Позиция найдена, но рядом есть похожие названия перечня — модель не уверена. '
    + 'Код-кандидат чаще всего верный: сверьте его и альтернативы.',
  not_found: 'Надёжного совпадения в перечне нет. Это не значит, что сервис не ответил: '
    + 'у перечня закрытый состав позиций.',
};

/** Текст под молчанием: различает «нет похожих» и «есть похожие, но не хватило уверенности». */
export function notFoundHint(result: Pick<Result, 'alternatives'>): string {
  if (result.alternatives.length > 0) {
    return 'Похожие позиции в перечне есть — возможно, товар назван иначе. '
      + 'Посмотрите альтернативы: это подсказка, а не ответ.';
  }
  return 'Похожих позиций нет: скорее всего, товара в перечне нет. '
    + 'Если он должен быть — уточните название или проверьте вручную.';
}

/**
 * Та же позиция в другом приложении перечня.
 *
 * В перечне 81 семейство позиций с одинаковым названием в приложениях 2 и 3
 * (например, «Мебель для офисов»: `31.01.1` и `31.01.11/31.01.12`). Код у них
 * разный, товар — один, и выбрать «единственно верный» нельзя. UI говорит об
 * этом прямо, вместо того чтобы выдавать один код за истину.
 */
export function duplicateAppendixHint(
  result: Pick<Result, 'title' | 'code' | 'alternatives'>,
): string | null {
  if (!result.code || !result.title) return null;
  const twin = result.alternatives.find(
    (alt) => alt.code && alt.code !== result.code && alt.title === result.title,
  );
  if (!twin) return null;
  return `Та же позиция есть в перечне под кодом ${twin.code}: `
    + 'код отличается приложением перечня, а не товаром.';
}

/** Подпись над кодом: в `review` это кандидат, в `ok` — ответ. */
export function codeLabel(status: Status): string {
  if (status === 'review') return 'Код-кандидат (проверьте)';
  if (status === 'ok') return 'Предполагаемый код ОКПД2';
  return 'Предполагаемый код ОКПД2';
}

/**
 * Пометка проверяющей ступени (LLM по top-3).
 *
 * Такой код — не ответ классификатора, а подтверждение одной из трёх
 * предложенных позиций, поэтому он всегда приходит со статусом `review`.
 * Отдельная строка важнее, чем процент уверенности: числа у такого ответа
 * нет (модель молчала), и показывать «0%» рядом с кодом было бы обманом.
 */
export function verifierNote(
  result: Pick<Result, 'verifier' | 'verifierNote'>,
): string | null {
  if (!result.verifier) return null;
  const detail = result.verifierNote ? ` (${result.verifierNote})` : '';
  return `Код подтверждён проверяющей моделью по трём ближайшим позициям${detail}. `
    + 'Это кандидат для проверки специалистом, а не заключение.';
}
